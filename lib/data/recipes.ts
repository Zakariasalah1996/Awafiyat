// دوال البحث والفلترة
export function getRecipesByCategory(category: RecipeCategory): Recipe[] {
  return RECIPES.filter((r) => r.category === category);
}

export function getRecipesByMealType(mealType: MealType): Recipe[] {
  return RECIPES.filter((r) => r.mealType.includes(mealType));
}

export function getRecipesByHealth(condition: HealthTag): Recipe[] {
  return RECIPES.filter(
    (r) => r.healthTags.includes(condition) || r.healthTags.includes("all")
  );
}

export function getQuickRecipes(): Recipe[] {
  return RECIPES.filter((r) => r.prepTime + r.cookTime <= 30);
}

export function getHeartyRecipes(): Recipe[] {
  return RECIPES.filter((r) => r.category === "hearty");
}

export function getHealthyRecipes(): Recipe[] {
  return RECIPES.filter((r) => r.category === "healthy");
}

export function searchRecipes(query: string): Recipe[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return RECIPES.filter(
    (r) =>
      r.name.includes(q) ||
      r.description.includes(q) ||
      r.ingredients.some((i) => i.name.includes(q))
  );
}

export function getRecipeById(id: string): Recipe | undefined {
  return RECIPES.find((r) => r.id === id);
}
